const enrichWithCountryFacts = `# Enrich the Reading List with Author Country Facts

Adds context to a reading list by pairing each book's author with facts about the country
they are associated with. Spans two protocols on purpose: the reading list is REST, the
country data is GraphQL, and an agent has to switch style between them.

## APIs used

| API | Protocol | What it provides |
| --- | --- | --- |
| Reading List API (\`${READING_LIST}\`) | REST | The shelf: id, title, author, status |
| countries-graphql (\`countries-graphql-v1.0\`) | GraphQL | Country name, capital, currency, languages |

Read each API's specification from the portal before calling it, and collect whatever
credentials its security scheme requires from the user. Never guess a token.

## Steps

1. **Read the shelf.** \`GET /books\` on the Reading List API. Expect 200 and an array of
   books. If the array is empty, stop and tell the user there is nothing to enrich.

2. **Resolve each author to a country.** This is not in either API - infer it from your own
   knowledge of the author, and record your confidence. Where you are unsure, say so rather
   than inventing a country.

3. **Fetch country facts.** For each distinct country, query countries-graphql:

   \`\`\`graphql
   query CountryFacts($code: ID!) {
     country(code: $code) {
       name
       capital
       currency
       languages { name }
     }
   }
   \`\`\`

   Use the ISO 3166-1 alpha-2 code. If \`country\` comes back null, treat the code as wrong
   and skip that author rather than retrying.

4. **Produce the digest.** One row per book: title, author, status, country, capital,
   currency, primary language, and your confidence in the author-to-country mapping.

## Constraints

- Read-only. Do not create, update or delete anything on the reading list.
- Batch the GraphQL queries by distinct country - do not issue one request per book.
- If a step fails with a 4xx, stop; only retry on 5xx, at most three times.
`;

