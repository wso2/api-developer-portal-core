#!/usr/bin/env node
/*
 * Seeds sample API workflows into an organization's default view.
 *
 *   node artifacts/api_flow_data.js [orgHandle] [viewName] [--prune]
 *
 * Defaults to `ashera100 default`. --prune also deletes workflows in that view which this
 * manifest does not define; without it, existing ones are left untouched. BASE_URL=... in
 * the environment overrides the spec URLs baked into the Arazzo sourceDescriptions, for
 * seeding a deployment other than the one config.json points at.
 *
 * It writes to whichever database config.json currently names - check with
 * `node use-db.js status` in the local-db tooling before running it.
 *
 * A companion to api_data.sh / org_data.sh / theme_data.sh, in Node rather than bash
 * because the agent prompt each workflow carries is generated by the application:
 * apiFlowService.generateAgentPrompt is what the create wizard calls, and hand-writing
 * that text into SQL would drift from it the first time the template changes.
 *
 * The workflows below target the three APIs a fresh test org tends to have - the REST
 * Reading List API, countries-graphql and chat-service - and between them cover every
 * state the settings list renders: both content types, PUBLISHED and DRAFT, PUBLIC and
 * PRIVATE, agent-visible and hidden. The Arazzo steps use that API's real operationIds
 * and real request schemas, so the workflow detail page and the source-description
 * check in the wizard both resolve instead of showing a broken reference.
 *
 * Re-running replaces the samples it owns (matched on handle) and leaves anything else
 * in the org alone, so it is safe after a dump restore.
 */
const path = require('path');

// src/db/sequelize and apiFlowService both read config.json via process.cwd().
const REPO_ROOT = path.resolve(__dirname, '..');
if (process.cwd() !== REPO_ROOT) process.chdir(REPO_ROOT);

const sequelize = require('../src/db/sequelize');
const adminDao = require('../src/dao/admin');
const apiMetadataDao = require('../src/dao/apiMetadata');
const apiFlowDao = require('../src/dao/apiFlow');
const { generateAgentPrompt } = require('../src/services/apiFlowService');
const config = require('../config.json');

const args = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const flags = new Set(process.argv.slice(2).filter((a) => a.startsWith('--')));

const ORG_HANDLE = args[0] || 'ashera100';
const VIEW_NAME = args[1] || 'default';
/* Spec URLs are absolute and must name the deployment the workflows will be read on, so
   this follows the DB the repo is pointed at rather than being hardcoded. BASE_URL
   overrides it when seeding a deployment whose config.json is not the one in hand. */
const BASE_URL = process.env.BASE_URL || config.baseUrl || 'https://localhost:3000';
/* Deletes workflows in this org/view that this manifest does not define. Off by default:
   it removes other people's work, so it has to be asked for. */
const PRUNE = flags.has('--prune');

/** The URL the wizard writes into sourceDescriptions for an API in this org. */
const specUrl = (apiHandle) =>
    `${BASE_URL}/${ORG_HANDLE}/views/${VIEW_NAME}/api/${apiHandle}/docs/specification.json`;

const READING_LIST = 'reading-list-api-v1.0';
const LOCAL_GATEWAY = 'local-gateway-v1.0';
const COUNTRIES = 'countries-graphql-v1.0';
