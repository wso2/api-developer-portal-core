async function main() {
    const orgID = await adminDao.getOrgId(ORG_HANDLE);
    if (!orgID) throw new Error(`organization not found: ${ORG_HANDLE}`);
    const viewId = await apiMetadataDao.getViewID(orgID, VIEW_NAME);
    if (!viewId) throw new Error(`view not found: ${ORG_HANDLE}/${VIEW_NAME}`);

    console.log(`org ${ORG_HANDLE} (${orgID})  view ${VIEW_NAME} (${viewId})`);
    console.log(`baseUrl ${BASE_URL}`);

    /* Which APIs this organization actually publishes, so a workflow is only seeded where
       every API it names can be resolved. */
    const publishedAPIs = await apiMetadataDao.getAPIMetadataByCondition({
        ORG_ID: orgID, STATUS: 'PUBLISHED',
    });
    const handles = new Set(publishedAPIs.map((a) => a.API_HANDLE));
    console.log(`published APIs: ${[...handles].sort().join(', ') || '(none)'}\n`);

    const applicable = [];
    for (const sample of SAMPLES) {
        const missing = (sample.requires || []).filter((h) => !handles.has(h));
        if (missing.length) {
            console.log(`  skipped   ${sample.handle}  (needs ${missing.join(', ')})`);
        } else {
            applicable.push(sample);
        }
    }

    if (PRUNE) {
        const keep = new Set(applicable.map((s) => s.handle));
        const existingAll = await apiFlowDao.getAllAPIFlows(orgID, viewId);
        for (const flow of existingAll) {
            if (keep.has(flow.HANDLE)) continue;
            const t = await sequelize.transaction();
            try {
                await apiFlowDao.deleteAPIFlow(orgID, viewId, flow.API_FLOW_ID, t);
                await t.commit();
                console.log(`  pruned    ${flow.HANDLE}  ("${flow.NAME}")`);
            } catch (error) {
                await t.rollback();
                throw error;
            }
        }
    }

    let created = 0;
    let replaced = 0;

    for (const sample of applicable) {
        const t = await sequelize.transaction();
        try {
            const existing = await apiFlowDao.getAPIFlowByHandle(orgID, viewId, sample.handle);
            if (existing) {
                await apiFlowDao.deleteAPIFlow(orgID, viewId, existing.API_FLOW_ID, t);
                replaced += 1;
            } else {
                created += 1;
            }

            await apiFlowDao.createAPIFlow(orgID, viewId, {
                name: sample.name,
                handle: sample.handle,
                description: sample.description,
                // Same call the create wizard makes, so these prompts match hand-made ones.
                agentPrompt: generateAgentPrompt(
                    sample.name, sample.description, [], ORG_HANDLE, VIEW_NAME, BASE_URL, sample.handle,
                ),
                status: sample.status,
                visibility: sample.visibility,
                agentVisibility: sample.agentVisibility,
                apiFlowDefinition: sample.content,
                contentType: sample.contentType,
            }, t);

            await t.commit();
            console.log(
                `  ${existing ? 'replaced' : 'created '}  ${sample.contentType.padEnd(8)}`
                + `${sample.status.padEnd(10)}${sample.handle}`,
            );
        } catch (error) {
            await t.rollback();
            console.error(`  FAILED    ${sample.handle}: ${error.message}`);
            throw error;
        }
    }

    console.log(`\n  ${created} created, ${replaced} replaced`);
    await sequelize.close();
}

main().catch((error) => {
    console.error(`\nerror: ${error.message}`);
    process.exit(1);
});
